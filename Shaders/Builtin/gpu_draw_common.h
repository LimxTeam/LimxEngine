// ============================================================================
// gpu_draw_common.h — GPU 驱动绘制的共享声明
//
// 逐物体数据被三方读: 剔除的计算着色器 (取包围球与绘制参数)、深度预通道的
// 顶点着色器、前向通道的顶点着色器 (取模型矩阵与材质下标)。
//
// **必须是同一份声明。** 三处各抄一遍的话, 字段顺序在其中一处写错的表现是
// "物体的变换与材质对不上号" —— 画面上像是场景数据坏了, 而不是着色器写错。
//
// row_major 与 C++ 侧 FMatrix 的行主序一致。漏掉的话矩阵整体转置, 物体会
// 出现在完全无关的位置。这个坑在分簇的两个计算着色器上踩过一次, 在阴影
// 图集上又差点踩第二次。
// ============================================================================

struct DrawObject {
    mat4 model;              //  0  世界变换
    vec4 boundsSphere;       // 64  xyz = 球心, w = 半径
    uvec4 drawParams;        // 80  x=索引数 y=首索引 z=顶点偏移 w=材质下标
};                           // 96
