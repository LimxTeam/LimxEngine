// ============================================================================
// reproject_common.h — 时域重投影的规则与有效性判定
//
// 从 taa.frag 里抽出来的, 目的与 sampling_common.h / meshlet_lod.h 一样:
// **让探针能验它**。
//
// 在此之前, 重投影的全部实现是 taa.frag 里的一行
//
//     vec2 historyUV = fragUV - velocity * 0.5;
//
// 三个约定压在这一行上 —— 符号 (当前减去位移)、0.5 (NDC 跨 2 个单位而 UV
// 跨 1 个)、Y 轴不翻 (Vulkan 的 NDC y 向下, 图像 UV y 也向下)。三者中任何
// 一个错了, 在缓慢运动下都只表现为"有点糊", 而"有点糊"没有人会当成 bug。
//
// 更要命的是唯一验 TAA 的那条判据 (RunTaaChecks) **全程相机静止**。静止时
// 速度恒为零, 于是 historyUV 恒等于 fragUV —— 上面三个约定一个都没被走到。
// 一个把 historyUV 写死成 fragUV 的实现在那条判据下拿满分。
//
// 所以这里的每个函数都必须满足两件事:
//   一、它是**纯函数** —— 输入全部显式, 于是 CPU 能独立实现同一个规则;
//   二、它的输出**可回读** —— 决策不能只活在混合结果里, 否则"接受率""历史
//       长度""半衰期"这几类判据全都无处取信号。
// ============================================================================

#ifndef LIMX_REPROJECT_COMMON_H
#define LIMX_REPROJECT_COMMON_H

// ============================================================================
// 重投影
// ============================================================================

/// 由本像素的 UV 与速度算出历史图上的采样坐标
///
/// velocityNdc 是 NDC 空间的**当前减上一帧**的差值 (gbuffer_common.h 里的
/// 速度约定)。推导:
///
///     uv = ndc * 0.5 + 0.5
///     uv_prev = ndc_prev * 0.5 + 0.5
///             = (ndc_cur - velocity) * 0.5 + 0.5
///             = uv_cur - velocity * 0.5
///
/// 三个约定各自的失效表现, 以及**静止的判据能不能看见它** (实测):
///
///   * 符号反 -> 历史往运动的反方向取, 位移加倍, 双倍拖影。
///     零速度乘任何符号都是零, 所以静止时仍是恒等映射 —— 现有的
///     --taa-check **完全看不见** (变异实测退出码 0)。
///
///   * 漏掉 0.5 -> 位移加倍。同上, 静止时零乘二还是零 ——
///     --taa-check 同样**完全看不见** (实测退出码 0)。
///
///   * 翻 Y -> 上下颠倒地取历史。这一条与前两条不同: 1 - uv.y 只在
///     uv.y = 0.5 那一行才是恒等, 别的行即使相机不动也取到镜像行, 所以
///     --taa-check 抓得住它 (实测退出码 11)。
///
/// 前两条是这个共享头存在的直接理由: 它们的错误只在**运动**时显形, 而在
/// 此之前没有任何一条判据让相机动过。
vec2 ReprojectToHistoryUV(vec2 currentUV, vec2 velocityNdc)
{
    return currentUV - velocityNdc * 0.5;
}

/// 历史坐标是否落在屏幕内
///
/// 落在屏幕外 = 这块内容上一帧还不存在, 没有历史可用。这是唯一一种**结构上**
/// 无法用历史的情形, 与"有历史但不是同一块表面"要分开算 —— 后者需要几何
/// 判定, 见 ReprojectSameSurface。
bool ReprojectIsOnScreen(vec2 uv)
{
    return uv.x >= 0.0 && uv.x <= 1.0 && uv.y >= 0.0 && uv.y <= 1.0;
}

// ============================================================================
// 有效性判定 —— "确实是同一块表面吗"
// ============================================================================

/// 重投影落点上的历史, 与本像素是不是同一块表面
///
/// 深度与法线**两项都要**, 缺任何一项都有一整类错误从"通过"那一侧溜走:
///
///   * 只验深度: 薄板的正反面深度几乎相同而法线相反 —— 前后两个平行表面
///     的历史会被当成有效, 表现为薄物体边缘的渗色。
///   * 只验法线: 同一朝向、不同距离的两个面 (例如走廊里前后两堵平行墙)
///     法线完全相同 —— 遮挡消失时后面那堵墙会直接继承前面那堵的历史。
///
/// 这两种错都不会让画面崩, 只会让它"有点脏", 所以必须靠判据钉, 而判据要能
/// 钉就必须让这两种情形在场景里**真的出现过** (对偶的两个构造集合都非空)。
///
/// 深度用**相对**容差: 绝对容差在近处过松、在远处过紧, 而同一个场景里两者
/// 会同时出现。相对容差让判定在整个深度范围上等价。
///
/// 法线用点积阈值。注意这里比的是**世界空间**法线 —— 相机一转, 视空间法线
/// 整体旋转, 于是"同一块表面"在视空间里点积不为 1。用视空间法线的话相机
/// 转动本身就会造成全屏拒绝, 而那看起来像"TAA 在运动时自动关掉了", 相当
/// 合理, 因此极难发现。
bool ReprojectSameSurface(float currentViewZ,
                          float historyViewZ,
                          vec3  currentNormal,
                          vec3  historyNormal,
                          float relativeDepthTolerance,
                          float normalDotThreshold)
{
    // 比较写成否定形式的对偶: 任何一项是 NaN 时下面两个比较都为假, 于是
    // 整体判为"不是同一块表面" —— 落在**丢弃历史**这一侧。
    //
    // 这是安全的一侧: 丢弃只损失一点收敛速度, 而接受一个 NaN 历史会把它
    // 传染给之后的每一帧 (指数滑动平均里 NaN 是吸收态)。第九天的教训是
    // NaN 会从正向比较里溜走, 这里让它溜进的正好是我们要的那一边。
    const float depthDelta = abs(currentViewZ - historyViewZ);
    const float depthLimit = relativeDepthTolerance * abs(currentViewZ);

    const bool depthMatches = depthDelta <= depthLimit;

    const bool normalMatches =
        dot(currentNormal, historyNormal) >= normalDotThreshold;

    return depthMatches && normalMatches;
}

// ============================================================================
// 历史长度
// ============================================================================

/// 本帧之后这个像素的历史长度
///
/// 接受则加一 (封顶), 拒绝则打回 1 —— "1"表示"只有本帧这一个样本"。
///
/// 打回 **1 而不是 0** 是必须的: 估计量是 累积和 / 长度, 长度为零会除零。
/// 而写成 0 之后再靠下游的 max(w, 1) 兜底的话, 回读出来的长度就不再等于
/// 真正参与平均的样本数, 于是"方差按 1/w 下降"那条判据验的是个假的 w。
///
/// 封顶的意义: 不封顶则权重无限增长, 新样本被 1/w 淹没, 表现为运动时画面
/// 越来越黏。封顶值必须是**显式输入**而不是这里的常量 —— 判据要能断言它,
/// 引擎内部常量判据看不见 (kMaxPathsPerDispatch 那条教训)。
uint ReprojectNextHistoryLength(uint previousLength, bool accepted, uint cap)
{
    if (!accepted)
    {
        return 1u;
    }

    return min(previousLength + 1u, cap);
}

#endif // LIMX_REPROJECT_COMMON_H
