// ============================================================================
// reproject_common.h — 时域重投影的规则与有效性判定
//
// 从 taa.frag 里抽出来的, 目的与 sampling_common.h / meshlet_lod.h 一样:
// **让探针能验它**。
//
// 在此之前, 重投影的全部实现是 taa.frag 里的一行
//
//     vec2 historyUV = fragUV - velocity * 0.5;
//
// 三个约定压在这一行上 —— 符号 (当前减去位移)、0.5 (NDC 跨 2 个单位而 UV
// 跨 1 个)、Y 轴不翻 (Vulkan 的 NDC y 向下, 图像 UV y 也向下)。三者中任何
// 一个错了, 在缓慢运动下都只表现为"有点糊", 而"有点糊"没有人会当成 bug。
//
// 更要命的是唯一验 TAA 的那条判据 (RunTaaChecks) **全程相机静止**。静止时
// 速度恒为零, 于是 historyUV 恒等于 fragUV —— 上面三个约定一个都没被走到。
// 一个把 historyUV 写死成 fragUV 的实现在那条判据下拿满分。
//
// 所以这里的每个函数都必须满足两件事:
//   一、它是**纯函数** —— 输入全部显式, 于是 CPU 能独立实现同一个规则;
//   二、它的输出**可回读** —— 决策不能只活在混合结果里, 否则"接受率""历史
//       长度""半衰期"这几类判据全都无处取信号。
// ============================================================================

#ifndef LIMX_REPROJECT_COMMON_H
#define LIMX_REPROJECT_COMMON_H

// ============================================================================
// 重投影
// ============================================================================

/// 由本像素的 UV 与速度算出历史图上的采样坐标
///
/// velocityNdc 是 NDC 空间的**当前减上一帧**的差值 (gbuffer_common.h 里的
/// 速度约定)。推导:
///
///     uv = ndc * 0.5 + 0.5
///     uv_prev = ndc_prev * 0.5 + 0.5
///             = (ndc_cur - velocity) * 0.5 + 0.5
///             = uv_cur - velocity * 0.5
///
/// 三个约定各自的失效表现, 以及**静止的判据能不能看见它** (实测):
///
///   * 符号反 -> 历史往运动的反方向取, 位移加倍, 双倍拖影。
///     零速度乘任何符号都是零, 所以静止时仍是恒等映射 —— 现有的
///     --taa-check **完全看不见** (变异实测退出码 0)。
///
///   * 漏掉 0.5 -> 位移加倍。同上, 静止时零乘二还是零 ——
///     --taa-check 同样**完全看不见** (实测退出码 0)。
///
///   * 翻 Y -> 上下颠倒地取历史。这一条与前两条不同: 1 - uv.y 只在
///     uv.y = 0.5 那一行才是恒等, 别的行即使相机不动也取到镜像行, 所以
///     --taa-check 抓得住它 (实测退出码 11)。
///
/// 前两条是这个共享头存在的直接理由: 它们的错误只在**运动**时显形, 而在
/// 此之前没有任何一条判据让相机动过。
vec2 ReprojectToHistoryUV(vec2 currentUV, vec2 velocityNdc)
{
    return currentUV - velocityNdc * 0.5;
}

/// 历史坐标是否落在屏幕内
///
/// 落在屏幕外 = 这块内容上一帧还不存在, 没有历史可用。这是唯一一种**结构上**
/// 无法用历史的情形, 与"有历史但不是同一块表面"要分开算 —— 后者需要几何
/// 判定, 而那个判定目前**还不存在** —— 见文件末尾那一段。
bool ReprojectIsOnScreen(vec2 uv)
{
    return uv.x >= 0.0 && uv.x <= 1.0 && uv.y >= 0.0 && uv.y <= 1.0;
}

// ============================================================================
// 有效性判定 —— 试过, 没成, 记在这里
// ============================================================================
//
// 这里原本要放一个 ReprojectSameSurface(深度, 法线) 的谓词: 重投影落点上的
// 历史与本像素不是同一块表面时**丢弃**历史, 而不是像现在这样交给邻域方差
// 裁剪去**钳制**。钳制是无条件执行的, 且不产生任何"我拒绝了"的信号, 于是
// 遮挡消失处的历史被夹进背景的邻域范围之后仍然是错的 —— 表现为拖影。
//
// 实现出来之后被 --taa-check 顶红了, 而且它是对的。实测:
//
//   * 拒绝率只有 **0.5%**, 但那 0.5% 全落在轮廓上;
//   * 全图 RMS 从 1.25 涨到 1.85 —— TAA 比不做还差。算得通: 0.5% 的像素
//     每个背约 19/255 的误差, 0.005 x 19² ≈ 1.8, 正是 RMS² 的增量。
//
// 根因: 判定读的是**带抖动**的深度缓冲。抖动每帧在像素内换采样位置, 轮廓
// 附近的像素于是每帧在前后两个表面之间跳 —— 每帧都判"不是同一块表面",
// 每帧都丢弃。而轮廓正是 TAA 存在的全部理由。
//
// 放宽阈值不解决问题: 容差是相对于**当前像素**深度的, 而轮廓上当前像素往往
// 很近 (z ≈ 1) 而历史落在远处 (z ≈ 100), 于是 |Δz| = 99 连 200% 的容差都
// 超。实测扫了六档 (深度 2%~200%, 法线 0.9~-0.9), RMS 从 1.85 降到 1.08,
// 而判据要的是 < 0.5 x 单帧 = 0.626 —— 一档都没到, 且趋势已经平掉。
//
// 于是换了判定的形状再试一次: 比历史几何的 **3x3 邻域**而不是正中那一个,
// 让亚像素的抖动落在邻域之内。--taa-check 通过了 —— 但它是**空操作**:
//
//   拒绝数 0 / 921600。位移从 0.6 加到 2.5 个单位, 仍然 0。
//
// 邻域是"任一 tap 对得上就接受", 而 showcase 场景的深度范围只有 30~43,
// 5% 的相对容差在 z=40 处是 2.0 个单位 —— 正是场景里物体之间的间隔量级;
// 法线阈值 0.8 (37 度) 又让大量共面表面互相匹配。**这个场景里没有真正的
// 近景遮挡远景**, 所以邻域里总有一个 tap 对得上。
//
// 两端都不通: 单点在轮廓上每帧拒绝, 邻域一个都不拒绝。中间需要的是有真实
// 深度分离的场景 + 重新定标, 而不是继续调参。
//
// ── 这中间还犯了一个更值得记的错 ──
//
// 邻域版本一度量出"静止 0, 平移后 35820" —— 看起来正是要的两侧结果。是假的。
//
// 探针当时放在出屏检查**之后**并提前返回, 于是出屏与无历史那两条路径的像素
// 根本没写标志, 带着正常着色的颜色; 而计数用的是"R 通道 < 64", 于是把画面里
// 所有**暗像素**都算成了拒绝。静止时没有出屏像素所以是 0, 平移后出现了所以
// 是 35820。谓词从头到尾一个都没拒绝过。
//
// 修法是给探针加一个"这个像素**走到了**这个判定吗"的通道, 只统计它为真的
// 像素。加上之后真相就出来了: 0。
//
// 这是同一个陷阱在同一天里的第三次现身, 而这一次在**判据自己的测量**里 ——
// 一个恒不发生的事件与一个"没测到"的事件读出来是同一个 0, 而 0 落在"通过"
// 那一侧。凡是数"某件事发生了几次"的判据, 都要同时数"有几个像素有资格发生
// 这件事", 否则两种零分不开。
//
// 下一个增量要的东西已经清楚: 一个有近景遮挡远景的场景, 加上探针的"走到了
// 判定"通道, 加上归因只在**被拒的像素**上统计 (在"任一 tap 对得上就接受"
// 的规则下, "某个 tap 被深度挡住"在邻域里几乎恒真, 与决策无关)。
//
// 在此之前不留没人调用的函数 —— 带着漂亮注释的死代码比没有更坏, 它看起来
// 像已经做过了。
//
// 记这一段是因为: 第一次失败是 --taa-check 抓出来的, 而那条判据此前被我判定
// "方向错了"(它对过度平滑没有反向约束)。两件事同时成立 —— 它确实缺一半,
// 但它对"历史被过度拒绝"这一半是有效的, 那天就靠它挡住了一次回归。

#endif // LIMX_REPROJECT_COMMON_H
