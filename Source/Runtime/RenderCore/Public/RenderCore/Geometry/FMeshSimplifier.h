// ============================================================
// 文件名称：FMeshSimplifier.h
// 创建时间：2026-09-02
// 创建者  ：LimxTeam
// 设计哲学：简化器给出的**误差必须是真实偏差的上界**。
//
//          这不是"精度要求"，是它下游那整套东西的地基：LOD 选择靠把这个
//          误差投到屏幕上、与阈值比，来决定画哪一层。误差报小了，选择就会
//          在该换层的时候不换 —— 而那在画面上是"模型突然变糙"或者更糟，
//          相邻两块选了不同层而边界对不上，出现裂缝。
//
//          所以本文件配的判据里，最要紧的那一条是：把**每一个原始顶点**
//          到简化后表面的距离量出来，取最大，必须 ≤ 报出来的误差。它不看
//          画面、不依赖场景，是一句能证伪的话。
//
//          第二要紧的是**单调**：记录下来的误差取的是"到目前为止的最大值"，
//          而不是这一次坍缩的代价。二次误差本身在邻居坍缩之后是会**变小**
//          的，直接记它会让第 N 层的误差小于第 N-1 层 —— 而 LOD 选择规则
//          ("自身误差 < 阈值且父误差 ≥ 阈值") 在那种数据上直接失效。
//
// 功能描述：二次误差度量 (QEM) 的边坍缩网格简化。
// 技术特性：逐顶点累加面积加权的平面二次型；坍缩位置在"解最优点 / 两端点 /
//          中点"里取误差最小且合法的；懒惰失效的二叉堆调度；坍缩前检查
//          三角形翻转与退化；按位置焊接重复顶点 (属性取平均)。
//
// ── 函数/方法表 ──────────────────────────────────────────────
// │ 函数名                    │ 描述                           │
// │──────────────────────────│───────────────────────────────│
// │ Simplify()               │ 简化到目标三角形数或误差上限    │
//
// ── 结构体表 ──────────────────────────────────────────────────
// │ 结构体名                   │ 描述                           │
// │──────────────────────────│───────────────────────────────│
// │ FMeshSimplifyOptions     │ 目标数、误差上限、边界策略      │
// │ FMeshSimplifyResult      │ 简化后的网格 + 达到的误差       │
//
// ── 更新历史 ──────────────────────────────────────────────────
// │ 日期         │ 作者       │ 描述                           │
// │─────────────│──────────│───────────────────────────────│
// │ 2026-09-02  │ LimxTeam  │ 初始创建                        │
// ============================================================

